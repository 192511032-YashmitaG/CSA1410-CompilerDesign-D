# run_outputs.py - prints the labelled output of every question (needs sdt.py in the same folder)
import sdt
def show(lines):
    for d, t in lines: print("  " * d + t)
def head(t): print("\n" + "=" * 70 + "\n" + t + "\n" + "=" * 70)

head("Q1: annotated parse tree for 3*(4+5)-6/2")
r = sdt.LParser(sdt.tokenize("3*(4+5)-6/2")).parse(); sdt.evaluate(r); sdt.height(r); show(sdt.tree_lines(r))
head("Q1: 10 test expressions (hand vs program)")
for x in sdt.q1_tests(): print(x)
head("Q1: height experiment (n, length, nodes, height-left, height-right) and nesting")
rows, nest = sdt.height_experiment(); [print(x) for x in rows]; [print(x) for x in nest]; print(sdt.assoc_demo())
head("Q2: declaration tests")
for x in sdt.q2_tests():
    print(x['src'], '->', 'OK' if x['ok'] else x['err'], x['table'])
    if x['ok']: show(sdt.decl_tree_lines(x['tree'])) if x['src'] == 'float a, b, c' else None
head("Q3: dependency graph, orders, cycle detection")
g = sdt.decl_graph("float a, b"); o, _ = g.kahn(); print("float a,b edges:", g.edges()); print("order:", o)
root, g3, top = sdt.expr_graph("2+3*4"); o1, _ = g3.kahn(); o2 = g3.dfs_order()
print("2+3*4 edges:", g3.edges()); print("Kahn:", o1, g3.run(o1)[top]); print("DFS :", o2, g3.run(o2)[top])
cg = sdt.cyclic_graph(); _, left = cg.kahn(); print("cycle detected:", " -> ".join(cg.find_cycle(left)))
head("Q4: postfix SDT")
res, sizes = sdt.q4_tests()
for x in res: print(x['e'], '->', x['pf'], '| reference ok:', x['ok'], '| actions:', x['act'], '| mid-action output:', x['mid'])
print("(tokens, actions, Q1 nodes, Q1 rules):", sizes)
head("Q5: parse tree vs AST")
for x in sdt.q5_counts()[0]: print("input, tokens, parse-tree nodes, AST nodes, topdown==bottomup:", x)
print("memory (n, parse bytes, AST bytes, ratio):", sdt.q5_memory())
a = sdt.ast_bottom_up(sdt.tokenize("a=b+c*d", single=False)); print("AST of a=b+c*d:"); show(sdt.ast_lines(a))
head("Q6: three-address code and marker stack trace")
print("\n".join(sdt.q6_tac("x = a + b * c - d")))
for t in sdt.marker_trace(): print(t)
head("Q7: MiniLang sample program -> TAC")
c, e, s, p = sdt.translate(sdt.SAMPLE, 'sdt'); print("\n".join(c)); print("errors:", e, "symbols:", s)
head("Q7: error tests")
for n, src in sdt.ERR_TESTS:
    c, e, s, p = sdt.translate(src, 'sdt'); print("--", n, "\n", "\n".join(c), "\n errors:", e)
head("Q7: timings (stmts, tokens, instr, one-pass ms, two-pass ms, same code, us/token, us/token)")
for x in sdt.timing(): print(x)
